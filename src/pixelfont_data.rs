pub(crate) fn glyph(c: char) -> Option<&'static [&'static str]> {
    let c = match c {
        'А' => 'A', 'В' => 'B', 'Е' => 'E', 'К' => 'K', 'М' => 'M', 'Н' => 'H',
        'О' => 'O', 'Р' => 'P', 'С' => 'C', 'Т' => 'T', 'Х' => 'X', '—' => '–',
        c => c,
    };
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, rows)| *rows)
}

